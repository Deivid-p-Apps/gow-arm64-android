//! x86-64 -> C static lifter.
//!
//! For every discovered function we decode with iced-x86 and emit C that
//! operates on a guest CPU state struct. Control flow goes through a single
//! dispatcher (`gow_call(rva)`) so that indirect calls, returns and jumps all
//! resolve through one address map — the standard approach used by existing
//! x86 static recompilers.
//!
//! Coverage is explicit: instructions we do not lift yet are emitted as a
//! `gow_unimpl` trap that records the RVA and opcode, so the port fails loudly
//! and incompletely-covered code is visible, never silently wrong.

use anyhow::Result;
use iced_x86::{Decoder, DecoderOptions, Formatter, Instruction, NasmFormatter, OpKind, Register};
use std::collections::BTreeSet;
use std::fmt::Write as _;

use crate::pe::PeImage;

pub struct LiftOutput {
    pub c_source: String,
    pub function_count: usize,
    pub instruction_count: usize,
    pub unimpl: BTreeSet<String>,
}

fn gpr32(r: Register) -> Option<&'static str> {
    use Register::*;
    let n = match r {
        EAX => "eax", ECX => "ecx", EDX => "edx", EBX => "ebx",
        ESP => "esp", EBP => "ebp", ESI => "esi", EDI => "edi",
        R8D => "r8d", R9D => "r9d", R10D => "r10d", R11D => "r11d",
        R12D => "r12d", R13D => "r13d", R14D => "r14d", R15D => "r15d",
        _ => return Option::None,
    };
    Some(n)
}

fn gpr64(r: Register) -> Option<&'static str> {
    use Register::*;
    let n = match r {
        RAX => "rax", RCX => "rcx", RDX => "rdx", RBX => "rbx",
        RSP => "rsp", RBP => "rbp", RSI => "rsi", RDI => "rdi",
        R8 => "r8", R9 => "r9", R10 => "r10", R11 => "r11",
        R12 => "r12", R13 => "r13", R14 => "r14", R15 => "r15",
        _ => return Option::None,
    };
    Some(n)
}

fn reg_name(r: Register) -> &'static str {
    if let Some(n) = gpr64(r) { return n; }
    if let Some(n) = gpr32(r) { return n; }
    use Register::*;
    match r {
        AL | AH | AX => "rax", CL | CH | CX => "rcx", DL | DH | DX => "rdx",
        BL | BH | BX => "rbx", SPL | SP => "rsp", BPL | BP => "rbp",
        SIL | SI => "rsi", DIL | DI => "rdi",
        R8L | R8W => "r8", R9L | R9W => "r9", R10L | R10W => "r10", R11L | R11W => "r11",
        R12L | R12W => "r12", R13L | R13W => "r13", R14L | R14W => "r14", R15L | R15W => "r15",
        _ => "rax",
    }
}

pub fn lift(pe: &PeImage, out_dir: &std::path::Path) -> Result<LiftOutput> {
    // Discover function entry points: .pdata + PE entry + TLS callbacks.
    let mut entries: BTreeSet<u32> = BTreeSet::new();
    for (start, _end) in &pe.pdata_functions {
        entries.insert(*start);
    }
    entries.insert(pe.entry_rva);
    if pe.tls_callback_va != 0 {
        if let Some(rva) = pe.va_to_rva(pe.tls_callback_va) {
            // The callback array is a list of VAs terminated by 0.
            let mut i = 0;
            while let Some(slot) = pe.read_rva(rva + i * 8, 8) {
                let va = u64::from_le_bytes(slot.try_into().unwrap());
                if va == 0 { break; }
                if let Some(cb) = pe.va_to_rva(va) { entries.insert(cb); }
                i += 1;
            }
        }
    }

    let mut c = String::new();
    writeln!(c, "/* Auto-generated by gowrecomp. Do not edit. */")?;
    writeln!(c, "#include \"gow_guest.h\"\n")?;

    let mut fmt = NasmFormatter::new();
    fmt.options_mut().set_hex_prefix("0x");
    fmt.options_mut().set_uppercase_hex(false);
    fmt.options_mut().set_space_after_operand_separator(true);

    let sections = pe.sections.clone();
    let image_base = pe.image_base;
    let mut func_count = 0usize;
    let mut insn_count = 0usize;
    let mut unimpl: BTreeSet<String> = BTreeSet::new();

    for &entry_rva in &entries {
        // Decode until we leave this function's .pdata range (or run off .text).
        let range_end = pe
            .pdata_functions
            .iter()
            .find(|(s, _)| *s == entry_rva)
            .map(|(_, e)| *e)
            .unwrap_or(entry_rva + 0x10000);

        let off = match PeImage::rva_to_off(&sections, entry_rva) { Some(o) => o, None => continue };
        let len = (range_end - entry_rva) as usize;
        if pe.bytes.len() < off + len { continue; }
        let code = &pe.bytes[off..off + len];

        writeln!(c, "void f_{entry_rva:x}(GowCpu* cpu) {{")?;
        func_count += 1;

        let mut dec = Decoder::with_ip(64, code, image_base + entry_rva as u64, DecoderOptions::NONE);
        let mut insn = Instruction::default();
        while dec.can_decode() {
            dec.decode_out(&mut insn);
            insn_count += 1;

            let rva = (insn.ip() - image_base) as u32;
            let mut text = String::new();
            fmt.format(&insn, &mut text);
            writeln!(c, "  /* 0x{rva:x}: {text} */")?;

            emit_instruction(&mut c, &insn, image_base, &mut unimpl)?;
        }
        writeln!(c, "}}\n")?;
    }

    // Dispatch table: rva -> function pointer.
    writeln!(c, "const GowFuncEntry gow_func_table[] = {{")?;
    for &rva in &entries {
        writeln!(c, "  {{ 0x{rva:x}u, f_{rva:x} }},")?;
    }
    writeln!(c, "  {{ 0u, 0 }}")?;
    writeln!(c, "}};")?;
    writeln!(c, "const unsigned gow_func_count = {};", entries.len())?;

    std::fs::create_dir_all(out_dir)?;
    std::fs::write(out_dir.join("gow_game.c"), &c)?;

    Ok(LiftOutput { c_source: c, function_count: func_count, instruction_count: insn_count, unimpl })
}

/// Emit C for a single instruction. Unsupported opcodes become explicit traps.
fn emit_instruction(
    c: &mut String,
    insn: &Instruction,
    image_base: u64,
    unimpl: &mut BTreeSet<String>,
) -> Result<()> {
    use iced_x86::Mnemonic::*;

    match insn.mnemonic() {
        Mov | Movzx | Movsx | Movsxd => {
            let dk = insn.op0_kind();
            let kind = insn.op1_kind();
            if dk == OpKind::Memory {
                let addr = mem_expr(insn, 0, image_base);
                let v = if kind == OpKind::Register {
                    format!("GOW_REG(cpu, {})", reg_name(insn.op1_register()))
                } else {
                    format!("0x{:x}ull", insn.immediate64())
                };
                writeln!(c, "  gow_store64(cpu, {addr}, {v});")?;
            } else {
            let dst = reg_name(insn.op0_register());
            if kind == OpKind::Register {
                let src = reg_name(insn.op1_register());
                writeln!(c, "  GOW_REG(cpu, {dst}) = GOW_REG(cpu, {src});")?;
            } else if kind == OpKind::Memory {
                let addr = mem_expr(insn, 1, image_base);
                writeln!(c, "  GOW_REG(cpu, {dst}) = gow_load64(cpu, {addr});")?;
            } else {
                let imm = insn.immediate64();
                writeln!(c, "  GOW_REG(cpu, {dst}) = 0x{imm:x}ull;")?;
            }
            }
        }
        Push => {
            if insn.op0_kind() == OpKind::Register {
                let src = reg_name(insn.op0_register());
                writeln!(c, "  gow_push64(cpu, GOW_REG(cpu, {src}));")?;
            } else {
                let imm = insn.immediate64();
                writeln!(c, "  gow_push64(cpu, 0x{imm:x}ull);")?;
            }
        }
        Pop => {
            let dst = reg_name(insn.op0_register());
            writeln!(c, "  GOW_REG(cpu, {dst}) = gow_pop64(cpu);")?;
        }
        Add | Sub | And | Or | Xor | Cmp | Test => {
            let dst = reg_name(insn.op0_register());
            let (op, want_flags) = match insn.mnemonic() {
                Add => ("+", true), Sub => ("-", true), And => ("&", true),
                Or => ("|", true), Xor => ("^", true), Cmp => ("-", true), Test => ("&", true),
                _ => unreachable!(),
            };
            let rhs = if insn.op1_kind() == OpKind::Register {
                format!("GOW_REG(cpu, {})", reg_name(insn.op1_register()))
            } else if insn.op1_kind() == OpKind::Memory {
                format!("gow_load64(cpu, {})", mem_expr(insn, 1, image_base))
            } else {
                format!("0x{:x}ull", insn.immediate64())
            };
            if want_flags {
                // Compute result and update flags via helper.
                writeln!(
                    c,
                    "  {{ uint64_t _a = GOW_REG(cpu, {dst}); uint64_t _b = {rhs}; uint64_t _r = _a {op} _b; gow_setflags(cpu, _a, _b, _r, {sz}); {} GOW_REG(cpu, {dst}) = _r; }}",
                    if insn.mnemonic() == Cmp || insn.mnemonic() == Test { "" } else { "" },
                    sz = insn.op0_register().size() as u32 * 8
                )?;
            }
        }
        Lea => {
            let dst = reg_name(insn.op0_register());
            let addr = mem_expr(insn, 1, image_base);
            writeln!(c, "  GOW_REG(cpu, {dst}) = {addr};")?;
        }
        Jmp => {
            if insn.op0_kind() == OpKind::NearBranch64 {
                let tgt = insn.near_branch64();
                let tgt_rva = tgt.wrapping_sub(image_base);
                if tgt_rva < 0x1_0000_0000 {
                    writeln!(c, "  gow_jump(cpu, 0x{tgt_rva:x}u); return;")?;
                }
            } else {
                writeln!(c, "  gow_jump(cpu, (uint32_t)GOW_REG(cpu, {})); return;", reg_name(insn.op0_register()))?;
            }
        }
        Call => {
            if insn.op0_kind() == OpKind::NearBranch64 {
                let tgt = insn.near_branch64();
                let tgt_rva = tgt.wrapping_sub(image_base);
                let ret = (insn.next_ip() - image_base) as u32;
                writeln!(c, "  gow_call(cpu, 0x{tgt_rva:x}u, 0x{ret:x}u);")?;
            } else {
                let r = reg_name(insn.op0_register());
                writeln!(c, "  gow_call_indirect(cpu, (uint32_t)GOW_REG(cpu, {r}));")?;
            }
        }
        Ret => {
            writeln!(c, "  gow_ret(cpu); return;")?;
        }
        Nop | Int3 | Endbr64 => {
            writeln!(c, "  /* {0} */", "nop")?;
        }
        _ => {
            let key = format!("{:?}", insn.mnemonic());
            unimpl.insert(key);
            let rva = (insn.ip() - image_base) as u32;
            writeln!(c, "  gow_unimpl(cpu, 0x{rva:x}u, {});", insn.mnemonic() as u32)?;
        }
    }
    Ok(())
}

fn mem_expr(insn: &Instruction, _idx: u32, image_base: u64) -> String {
    let base = insn.memory_base();
    let index = insn.memory_index();
    let disp = insn.memory_displacement64();
    let scale = insn.memory_index_scale();
    let mut e = String::new();
    if base != Register::None {
        if base == Register::RIP {
            let _ = write!(e, "0x{:x}ull", disp);
        } else {
            let b = reg_name(base);
            let _ = write!(e, "GOW_REG(cpu, {b})");
        }
    } else if disp != 0 || index == Register::None {
        let _ = write!(e, "0x{disp:x}ull");
    }
    if index != Register::None {
        let ix = reg_name(index);
        if !e.is_empty() { e.push_str(" + "); }
        let _ = write!(e, "GOW_REG(cpu, {ix}) * {scale}");
    }
    if base != Register::None && base != Register::RIP && disp != 0 {
        let _ = write!(e, " + 0x{disp:x}ull");
    }
    let _ = image_base;
    if e.is_empty() { e.push('0'); }
    e
}
